-- Inventario ---------------------------------------------------------

-- Descuenta insumos de un pedido según recetas. Idempotente.
create or replace function public.discount_inventory_for_order(p_order_id bigint, p_by text default '')
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  o record;
begin
  select * into o from orders where id = p_order_id for update;
  if o.id is null then
    raise exception 'Pedido no encontrado.';
  end if;
  perform public.assert_branch_access(o.branch_id);
  if o.inventory_discounted or o.status = 'Cancelado' then
    return;
  end if;

  with consumo as (
    select r.ingredient_id, sum(r.quantity * oi.quantity) as qty
    from order_items oi
    join recipe_items r on r.product_id = oi.product_id
    where oi.order_id = o.id
    group by r.ingredient_id
  ),
  upd as (
    insert into ingredient_stock as s (branch_id, ingredient_id, business_id, stock)
    select o.branch_id, c.ingredient_id, o.business_id, -c.qty from consumo c
    on conflict (branch_id, ingredient_id)
      do update set stock = s.stock + excluded.stock  -- excluded.stock ya es negativo
    returning s.ingredient_id
  )
  insert into inventory_movements
    (business_id, branch_id, ingredient_id, ingredient_name, type, quantity, unit, order_id, order_folio, created_by)
  select o.business_id, o.branch_id, i.id, i.name, 'Venta POS', c.qty, i.unit, o.id, o.folio, coalesce(p_by, '')
  from consumo c join ingredients i on i.id = c.ingredient_id;

  update orders set inventory_discounted = true where id = o.id;
end;
$$;

create or replace function public.adjust_inventory(
  p_branch_id      uuid,
  p_ingredient_id  bigint,
  p_quantity       numeric,
  p_type           text,
  p_reason         text,
  p_by             text default ''
)
returns numeric
language plpgsql
security definer
set search_path = public
as $$
declare
  v_business  uuid := public.assert_branch_access(p_branch_id);
  v_ing       record;
  v_delta     numeric;
  v_stock     numeric;
begin
  if p_quantity is null or p_quantity <= 0 then
    raise exception 'La cantidad debe ser mayor a cero.';
  end if;
  if coalesce(trim(p_reason), '') = '' then
    raise exception 'El motivo del ajuste es obligatorio.';
  end if;
  if p_type not in ('Ajuste positivo', 'Ajuste negativo') then
    raise exception 'Tipo de ajuste inválido.';
  end if;

  select * into v_ing from ingredients where id = p_ingredient_id and business_id = v_business;
  if v_ing.id is null then
    raise exception 'Ingrediente no encontrado.';
  end if;

  v_delta := case when p_type = 'Ajuste positivo' then p_quantity else -p_quantity end;

  insert into ingredient_stock as s (branch_id, ingredient_id, business_id, stock)
    values (p_branch_id, p_ingredient_id, v_business, v_delta)
    on conflict (branch_id, ingredient_id) do update set stock = s.stock + v_delta
    returning s.stock into v_stock;

  insert into inventory_movements
    (business_id, branch_id, ingredient_id, ingredient_name, type, quantity, unit, reason, created_by)
    values (v_business, p_branch_id, v_ing.id, v_ing.name, p_type, p_quantity, v_ing.unit, trim(p_reason), coalesce(p_by, ''));

  return v_stock;
end;
$$;

-- Alta/edición de ingrediente desde Configuración. Si cambia la
-- existencia, queda registrado en el Kardex.
create or replace function public.save_ingredient(
  p_branch_id  uuid,
  p_id         bigint,
  p_name       text,
  p_unit       text,
  p_minimum    numeric,
  p_stock      numeric,
  p_cost       numeric default 0,
  p_by         text default ''
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_business  uuid := public.assert_branch_access(p_branch_id);
  v_id        bigint;
  v_current   numeric;
  v_diff      numeric;
begin
  if coalesce(trim(p_name), '') = '' then
    raise exception 'El ingrediente necesita nombre.';
  end if;
  if coalesce(p_minimum, 0) < 0 or coalesce(p_stock, 0) < 0 then
    raise exception 'Stock y mínimo no pueden ser negativos.';
  end if;

  if p_id is null then
    insert into ingredients (business_id, name, unit, minimum, cost)
      values (v_business, trim(p_name), p_unit, coalesce(p_minimum, 0), coalesce(p_cost, 0))
      returning id into v_id;
    -- existencia en cero para todas las sucursales
    insert into ingredient_stock (branch_id, ingredient_id, business_id, stock)
      select b.id, v_id, v_business, 0 from branches b where b.business_id = v_business;
  else
    update ingredients set name = trim(p_name), unit = p_unit, minimum = coalesce(p_minimum, 0),
      cost = coalesce(p_cost, cost)
    where id = p_id and business_id = v_business
    returning id into v_id;
    if v_id is null then
      raise exception 'Ingrediente no encontrado.';
    end if;
  end if;

  select stock into v_current from ingredient_stock where branch_id = p_branch_id and ingredient_id = v_id;
  v_diff := coalesce(p_stock, 0) - coalesce(v_current, 0);

  if v_diff <> 0 then
    perform public.adjust_inventory(
      p_branch_id, v_id, abs(v_diff),
      case when v_diff > 0 then 'Ajuste positivo' else 'Ajuste negativo' end,
      'Edición desde catálogo de ingredientes', p_by
    );
  end if;

  return v_id;
end;
$$;

