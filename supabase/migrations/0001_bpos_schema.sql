-- Lanza error si la cuenta no pertenece al negocio de la sucursal
create or replace function public.assert_branch_access(p_branch_id uuid)
returns uuid
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_business uuid;
begin
  select business_id into v_business from public.branches where id = p_branch_id;
  if v_business is null or not public.is_member(v_business) then
    raise exception 'SIN_ACCESO' using errcode = '42501';
  end if;
  return v_business;
end;
$$;

