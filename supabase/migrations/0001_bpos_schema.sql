create table public.businesses (
  id          uuid primary key default gen_random_uuid(),
  name        text not null check (length(trim(name)) > 0),
  plan        text not null default 'free',
  owner_id    uuid references auth.users (id) on delete set null,
  created_at  timestamptz not null default now()
);

create table public.branches (
  id               uuid primary key default gen_random_uuid(),
  business_id      uuid not null references public.businesses (id) on delete cascade,
  name             text not null check (length(trim(name)) > 0),
  address          text not null default '',
  phone            text not null default '',
  report_whatsapp  text not null default '',  -- a dónde se manda el corte de caja
  ticket_footer    text not null default '',
  created_at       timestamptz not null default now()
);
create index branches_business_idx on public.branches (business_id);

create table public.business_members (
  business_id  uuid not null references public.businesses (id) on delete cascade,
  user_id      uuid not null references auth.users (id) on delete cascade,
  role         text not null default 'owner' check (role in ('owner', 'admin', 'device')),
  created_at   timestamptz not null default now(),
  primary key (business_id, user_id)
);
create index business_members_user_idx on public.business_members (user_id);

-- ¿La cuenta actual pertenece a este negocio?
create or replace function public.is_member(p_business_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.business_members m
    where m.business_id = p_business_id and m.user_id = auth.uid()
  );
$$;

create or replace function public.branch_business(p_branch_id uuid)
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select business_id from public.branches where id = p_branch_id;
$$;

