-- Alta de negocio: la cuenta que lo crea queda como dueña.
create or replace function public.bootstrap_business(
  p_business_name text,
  p_branch_name   text,
  p_admin_name    text,
  p_admin_pin     text,
  p_seed_catalog  boolean default true
)
returns json
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_uid       uuid := auth.uid();
  v_business  uuid;
  v_branch    uuid;
begin
  if v_uid is null then
    raise exception 'NO_AUTENTICADO' using errcode = '42501';
  end if;
  if coalesce(trim(p_business_name), '') = '' then
    raise exception 'Falta el nombre del negocio.';
  end if;
  if coalesce(trim(p_admin_name), '') = '' then
    raise exception 'Falta el nombre del administrador.';
  end if;
  if p_admin_pin !~ '^[0-9]{4,8}$' then
    raise exception 'El PIN debe tener de 4 a 8 dígitos.';
  end if;

  insert into businesses (name, owner_id) values (trim(p_business_name), v_uid)
    returning id into v_business;
  insert into branches (business_id, name)
    values (v_business, coalesce(nullif(trim(p_branch_name), ''), 'Matriz'))
    returning id into v_branch;
  insert into business_members (business_id, user_id, role) values (v_business, v_uid, 'owner');
  insert into branch_counters (branch_id) values (v_branch);
  insert into employees (business_id, name, role, pin_hash)
    values (v_business, trim(p_admin_name), 'Admin', crypt(p_admin_pin, gen_salt('bf')));

  insert into station_printers (branch_id, business_id, station)
