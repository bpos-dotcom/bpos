-- Tablas operativas: acceso completo para miembros del negocio
do $$
declare
  t text;
begin
  foreach t in array array[
    'products', 'ingredients', 'ingredient_stock', 'recipe_items',
    'cash_shifts', 'cash_movements', 'orders', 'order_items',
    'inventory_movements', 'purchases', 'purchase_aliases',
    'station_printers', 'print_jobs', 'bridge_aliases', 'bridge_tickets'
  ] loop
    execute format(
      'create policy %I on public.%I for all to authenticated
         using (public.is_member(business_id))
         with check (public.is_member(business_id))',
      t || '_member_all', t
    );
  end loop;
end;
$$;

-- branch_counters: solo lo toca create_order (security definer)

-- Permisos explícitos (no dependemos de los permisos por defecto del
-- proyecto). RLS decide QUÉ filas ve cada cuenta; esto decide QUÉ puede
-- intentar. Los anónimos (sin cuenta) no tienen acceso a nada.
grant usage on schema public to authenticated;
revoke all on all tables in schema public from anon;
revoke all on all sequences in schema public from anon;
grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- El PIN cifrado nunca sale de la base de datos
revoke all on public.employees from anon, authenticated;
grant select (id, business_id, name, role, active, created_at) on public.employees to authenticated;

revoke all on public.branch_counters from anon, authenticated;

-- Ventas e inventario se escriben por funciones para mantener folios y
-- existencias consistentes; desde el cliente solo se permite actualizar
-- el estado de cocina (KDS).
revoke insert, delete on public.orders from anon, authenticated;
revoke update on public.orders from anon, authenticated;
grant update (kds_status, kds_released, kds_completed) on public.orders to authenticated;
revoke insert, update, delete on public.order_items from anon, authenticated;
revoke insert, update, delete on public.inventory_movements from anon, authenticated;
revoke insert, update, delete on public.ingredient_stock from anon, authenticated;
revoke insert, update, delete on public.purchases from anon, authenticated;

