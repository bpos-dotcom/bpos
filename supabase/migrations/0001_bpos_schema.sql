create or replace function public.save_employee(
  p_business_id uuid,
  p_id          bigint,
  p_name        text,
  p_role        text,
  p_active      boolean,
  p_pin         text default null
)
returns bigint
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_id bigint;
begin
  if not public.is_member(p_business_id) then
    raise exception 'SIN_ACCESO' using errcode = '42501';
  end if;
  if coalesce(trim(p_name), '') = '' then
