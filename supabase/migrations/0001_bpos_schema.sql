-- Importación desde la versión local (localStorage). Inserta registros
-- históricos tal cual, sin recalcular inventario.
create or replace function public.import_order(p_branch_id uuid, p_order jsonb, p_items jsonb)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_business  uuid := public.assert_branch_access(p_branch_id);
  v_folio     integer := (p_order->>'folio')::integer;
  v_id        bigint;
begin
  if exists (select 1 from orders where branch_id = p_branch_id and folio = v_folio) then
    return null; -- ya importado
  end if;

  insert into orders (
    business_id, branch_id, folio, created_at, order_type, customer_name, customer_phone,
    customer_address, payment_method, subtotal, discount, total, source, external_order_number,
    kds_status, kds_released, kds_completed, inventory_discounted, created_by
  ) values (
    v_business, p_branch_id, v_folio,
    coalesce((p_order->>'created_at')::timestamptz, now()),
    coalesce(p_order->>'order_type', 'Mostrador'),
    coalesce(p_order->>'customer_name', ''),
    coalesce(p_order->>'customer_phone', ''),
    coalesce(p_order->>'customer_address', ''),
    coalesce(p_order->>'payment_method', 'Efectivo'),
    coalesce((p_order->>'subtotal')::numeric, 0),
    coalesce((p_order->>'discount')::numeric, 0),
    coalesce((p_order->>'total')::numeric, 0),
    coalesce(p_order->>'source', 'POS'),
    p_order->>'external_order_number',
    coalesce(p_order->>'kds_status', 'Entregado'),
    true, true, true, 'Importación'
  ) returning id into v_id;

  insert into order_items (business_id, order_id, product_id, name, category, emoji, station, price, quantity)
  select v_business, v_id,
         (select p.id from products p where p.id = nullif(i->>'product_id', '')::bigint and p.business_id = v_business),
         coalesce(i->>'name', 'Producto'), coalesce(i->>'category', ''), coalesce(i->>'emoji', ''),
         coalesce(nullif(i->>'station', ''), 'Cocina'),
         coalesce((i->>'price')::numeric, 0), greatest(coalesce((i->>'quantity')::numeric, 1), 0.001)
  from jsonb_array_elements(p_items) i;

  update branch_counters set last_order_folio = greatest(last_order_folio, v_folio)
  where branch_id = p_branch_id;

  return v_id;
end;
$$;

-- Fija existencias directo (solo importación inicial)
create or replace function public.import_stock(p_branch_id uuid, p_ingredient_id bigint, p_stock numeric)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_business uuid := public.assert_branch_access(p_branch_id);
