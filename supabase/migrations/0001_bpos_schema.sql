-- Crea un pedido completo en una sola transacción:
--   folio por sucursal + partidas + (opcional) descuento de inventario.
-- p_order: { order_type, customer_name, customer_phone, customer_address,
--            payment_method, discount, cash_received, card_amount,
--            transfer_amount, source, external_order_number, kds_released,
--            discount_inventory, require_open_shift, created_by }
-- p_items: [{ product_id, name, category, emoji, station, price, quantity }]
create or replace function public.create_order(p_branch_id uuid, p_order jsonb, p_items jsonb)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_business  uuid := public.assert_branch_access(p_branch_id);
  v_shift     bigint;
  v_folio     integer;
  v_subtotal  numeric;
  v_discount  numeric := greatest(coalesce((p_order->>'discount')::numeric, 0), 0);
  v_total     numeric;
  v_paid      numeric;
  v_order     orders;
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'El pedido no tiene productos.';
  end if;

  select id into v_shift from cash_shifts where branch_id = p_branch_id and status = 'open';
  if v_shift is null and coalesce((p_order->>'require_open_shift')::boolean, false) then
    raise exception 'CAJA_CERRADA: Primero debes abrir la caja antes de cobrar.';
  end if;

  select coalesce(sum((i->>'price')::numeric * (i->>'quantity')::numeric), 0)
    into v_subtotal
    from jsonb_array_elements(p_items) i;
  v_total := greatest(v_subtotal - v_discount, 0);

  update branch_counters set last_order_folio = last_order_folio + 1
    where branch_id = p_branch_id
    returning last_order_folio into v_folio;
  if v_folio is null then
    insert into branch_counters (branch_id, last_order_folio) values (p_branch_id, 1)
      on conflict (branch_id) do update set last_order_folio = branch_counters.last_order_folio + 1
      returning last_order_folio into v_folio;
  end if;

  v_paid := coalesce((p_order->>'cash_received')::numeric, 0)
          + coalesce((p_order->>'card_amount')::numeric, 0)
          + coalesce((p_order->>'transfer_amount')::numeric, 0);

  insert into orders (
    business_id, branch_id, folio, shift_id, order_type, customer_name, customer_phone,
    customer_address, payment_method, subtotal, discount, total, cash_received, card_amount,
    transfer_amount, change_given, source, external_order_number, kds_released, created_by
  ) values (
    v_business, p_branch_id, v_folio, v_shift,
    coalesce(p_order->>'order_type', 'Mostrador'),
    coalesce(p_order->>'customer_name', ''),
    coalesce(p_order->>'customer_phone', ''),
    coalesce(p_order->>'customer_address', ''),
    coalesce(p_order->>'payment_method', 'Efectivo'),
    v_subtotal, v_discount, v_total,
    coalesce((p_order->>'cash_received')::numeric, 0),
    coalesce((p_order->>'card_amount')::numeric, 0),
    coalesce((p_order->>'transfer_amount')::numeric, 0),
    case when coalesce(p_order->>'payment_method', 'Efectivo') in ('Efectivo', 'Mixto')
         then greatest(v_paid - v_total, 0) else 0 end,
    coalesce(p_order->>'source', 'POS'),
    p_order->>'external_order_number',
    coalesce((p_order->>'kds_released')::boolean, true),
    coalesce(p_order->>'created_by', '')
  ) returning * into v_order;

  insert into order_items (business_id, order_id, product_id, name, category, emoji, station, price, quantity)
  select v_business, v_order.id,
         -- solo enlaza productos que existen en este negocio
         (select p.id from products p where p.id = nullif(i->>'product_id', '')::bigint and p.business_id = v_business),
         coalesce(i->>'name', 'Producto'),
         coalesce(i->>'category', ''),
         coalesce(i->>'emoji', ''),
         coalesce(nullif(i->>'station', ''), 'Cocina'),
         coalesce((i->>'price')::numeric, 0),
         (i->>'quantity')::numeric
  from jsonb_array_elements(p_items) i;

  if coalesce((p_order->>'discount_inventory')::boolean, true) then
    perform public.discount_inventory_for_order(v_order.id, coalesce(p_order->>'created_by', ''));
  end if;

  return json_build_object('id', v_order.id, 'folio', v_order.folio, 'created_at', v_order.created_at,
                           'subtotal', v_order.subtotal, 'total', v_order.total, 'shift_id', v_order.shift_id);
end;
$$;

-- Cancela un pedido (no se borra: queda para auditoría) y regresa insumos
create or replace function public.cancel_order(p_order_id bigint, p_reason text, p_by text default '')
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  o record;
begin
  select * into o from orders where id = p_order_id for update;
  if o.id is null then
    raise exception 'Pedido no encontrado.';
  end if;
  perform public.assert_branch_access(o.branch_id);
  if o.status = 'Cancelado' then
    return;
  end if;

  if o.inventory_discounted then
    with devol as (
      select ingredient_id, ingredient_name, unit, sum(quantity) as qty
      from inventory_movements
      where order_id = o.id and type = 'Venta POS' and ingredient_id is not null
      group by ingredient_id, ingredient_name, unit
    ),
    upd as (
      update ingredient_stock s set stock = s.stock + d.qty
      from devol d
      where s.branch_id = o.branch_id and s.ingredient_id = d.ingredient_id
      returning s.ingredient_id
    )
    insert into inventory_movements
      (business_id, branch_id, ingredient_id, ingredient_name, type, quantity, unit, order_id, order_folio, reason, created_by)
    select o.business_id, o.branch_id, d.ingredient_id, d.ingredient_name, 'Ajuste positivo', d.qty, d.unit,
           o.id, o.folio, 'Cancelación de pedido #' || lpad(o.folio::text, 6, '0'), coalesce(p_by, '')
    from devol d;
  end if;

  update orders set status = 'Cancelado', cancel_reason = coalesce(p_reason, ''),
                    kds_completed = true, inventory_discounted = false
  where id = o.id;
end;
$$;

