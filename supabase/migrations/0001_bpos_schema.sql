-- =====================================================================
-- B-POS (Burger Planet OS) · Bloque 11 · Esquema Supabase
-- ---------------------------------------------------------------------
-- Multi-negocio (SaaS) y multi-sucursal desde el día uno.
--   negocio (businesses) ─┬─ sucursales (branches)
--                         ├─ cuentas con acceso (business_members → auth.users)
--                         ├─ empleados con PIN (employees)
--                         ├─ catálogo: products, ingredients, recipe_items
--                         └─ operación por sucursal: stock, ventas, caja,
--                            kardex, compras, impresiones, Bridge
--
-- Seguridad: Row Level Security en TODAS las tablas. Una cuenta solo ve
-- los datos de los negocios donde es miembro. Las operaciones que tocan
-- varias tablas (venta + inventario, compras, PIN) son funciones
-- atómicas (RPC) para que dos cajas al mismo tiempo no se pisen.
--
-- Cómo aplicarlo: Supabase → SQL Editor → pegar todo → Run.
-- Es seguro correrlo una sola vez en un proyecto nuevo.
-- =====================================================================

create extension if not exists pgcrypto with schema extensions;

